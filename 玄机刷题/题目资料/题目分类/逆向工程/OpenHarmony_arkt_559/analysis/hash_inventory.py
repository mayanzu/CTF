"""Write a SHA-256 inventory of all files in the #559 evidence directory.

The inventory excludes itself because its own digest would be recursive. The
script and every other file, including original attachments and logs, are listed.
"""
from __future__ import annotations

import hashlib
import platform
import sys
from datetime import datetime
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
OUTPUT = Path(__file__).resolve().parent / "SHA256_INVENTORY_20260929.txt"
RUN_LOG = Path(__file__).resolve().parent / "SHA256_INVENTORY_RUN_20260929.txt"


def main() -> None:
    records = []
    excluded = {OUTPUT, RUN_LOG}
    for path in sorted(p for p in ROOT.rglob("*") if p.is_file() and p not in excluded):
        digest = hashlib.sha256(path.read_bytes()).hexdigest().upper()
        relative = path.relative_to(ROOT).as_posix()
        records.append(f"{digest}  {path.stat().st_size:>10}  {relative}")
    text = (
        "# SHA-256 inventory for Xuanji challenge #559 materials\n"
        "# Generated by analysis/hash_inventory.py with Python standard library.\n"
        "# Includes all files under this challenge directory except this inventory and its run log.\n"
        + "\n".join(records)
        + "\n"
    )
    inventory_digest = hashlib.sha256(text.encode("utf-8")).hexdigest().upper()
    check_only = len(sys.argv) == 2 and sys.argv[1] == "--check"
    if len(sys.argv) > 1 and not check_only:
        raise SystemExit("usage: python hash_inventory.py [--check]")
    if check_only:
        if not OUTPUT.exists() or OUTPUT.read_text(encoding="utf-8") != text:
            raise SystemExit("HASH_INVENTORY_CHECK=FAIL")
        print("HASH_INVENTORY_CHECK=PASS")
        print(f"INVENTORY_PATH={OUTPUT}")
        print(f"INVENTORY_ENTRIES={len(records)}")
        print(f"INVENTORY_SHA256={inventory_digest}")
        return

    OUTPUT.write_text(text, encoding="utf-8", newline="\n")
    run_log = (
        "COMMAND> python -B -u .\\analysis\\hash_inventory.py\n"
        f"RUN_UTC_LOCAL={datetime.now().astimezone().isoformat(timespec='seconds')}\n"
        f"PYTHON_VERSION={platform.python_version()}\n"
        f"INVENTORY_PATH={OUTPUT}\n"
        f"INVENTORY_ENTRIES={len(records)}\n"
        f"INVENTORY_SHA256={inventory_digest}\n"
        "EXIT_CODE=0\n"
    )
    RUN_LOG.write_text(run_log, encoding="utf-8", newline="\n")
    print(f"INVENTORY_PATH={OUTPUT}")
    print(f"INVENTORY_ENTRIES={len(records)}")
    print(f"INVENTORY_SHA256={inventory_digest}")
    print(f"RUN_LOG={RUN_LOG}")


if __name__ == "__main__":
    main()
